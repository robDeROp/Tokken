const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({ lang: 'nl', setLang: () => {}, t: nl });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('nl');
  useEffect(() => {
    try { const l = localStorage.getItem('tokken:lang'); if (l === 'en' || l === 'nl') setLangState(l); } catch { /* ignore */ }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('tokken:lang', l); } catch { /* ignore */ }
  };
  return <LangCtx.Provider value={{ lang, setLang, t: lang === 'en' ? en : nl }}>{children}</LangCtx.Provider>;
}

export const useT = () => useContext(LangCtx);

export function LangToggle() {
  const { lang, setLang } = useT();
  return (
    <div className="lang">
      <button className={lang === 'nl' ? 'on' : ''} onClick={() => setLang('nl')}>NL</button>
      <button className={lang === 'en' ? 'on' : ''} onClick={() => setLang('en')}>EN</button>
    </div>
  );
}
